async function helper(route) {
 const {port,token}=JSON.parse(await fs.readFile(helperPath,'utf8'));
 const result=await fetch(`http://127.0.0.1:${port}${route}`,{method:'POST',headers:{Authorization:`Bearer ${token}`}});
 if(!result.ok)throw Error(await result.text());
 return result.json();
}
async function waitFor(action,accept,timeout=20000){
 const end=Date.now()+timeout;
 while(Date.now()<end){
   const value=await action();
   if(accept(value))return value;
   await sleep(400);
 }
 throw Error('Timed out waiting for the editor');
}
async function driver(){
 const info=await(await fetch(`http://127.0.0.1:${port}/json/version`)).json();
 const ws=new WebSocket(info.webSocketDebuggerUrl);
 await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
 const waiting=new Map();
 ws.addEventListener('message',({data})=>{const msg=JSON.parse(data);if(!msg.id)return;const p=waiting.get(msg.id);waiting.delete(msg.id);if(msg.error)p?.reject(new Error(msg.error.message));else p?.resolve(msg.result);});
 let id=0;
 const send=(method,params={},sessionId)=>new Promise((resolve,reject)=>{const n=++id;waiting.set(n,{resolve,reject});ws.send(JSON.stringify({id:n,method,params,sessionId}));});
 await helper('/open');
 const target=await waitFor(async()=> (await send('Target.getTargets')).targetInfos.find(t=>t.type==='iframe'&&t.url.startsWith('vscode-webview:')),Boolean,20000);
 const {sessionId}=await send('Target.attachToTarget',{targetId:target.targetId,flatten:true});
 async function ui(body){
  const expression=`(()=>{const d=document.querySelector('iframe#active-frame')?.contentDocument; if(!d?.querySelector('#prompt'))return null; ${body}})()`;
  const r=await send('Runtime.evaluate',{expression,returnByValue:true},sessionId);
  if(r.exceptionDetails)throw Error(r.exceptionDetails.exception?.description??r.exceptionDetails.text);
  return r.result.value;
 }
 await waitFor(()=>ui('return true'),Boolean,20000);
 return ui;
}
